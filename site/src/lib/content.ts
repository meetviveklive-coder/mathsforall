/**
 * Build-time access to the curriculum and topic files in the repository root.
 * Production builds include only topics with status "approved".
 * `astro build --mode preview` also includes "verified" and "draft" topics, clearly labelled.
 */
import fs from 'node:fs';
import path from 'node:path';

export const REPO_ROOT = path.resolve(process.cwd(), '..');
export const IS_PREVIEW = import.meta.env.MODE === 'preview' || import.meta.env.DEV;

export interface MapTopic {
  id: string;
  title: string;
  stage: number;
  unit?: string;
  prerequisites: string[];
  objectives: string[];
  est_minutes: number;
}

export interface TopicMap {
  stages: { stage: number; name: string; summary?: string }[];
  topics: MapTopic[];
}

export interface Option { text: string; value?: string; correct: boolean; why_wrong?: string }
export interface Question {
  id: string;
  type: 'numeric' | 'mcq' | 'true_false' | 'text';
  prompt: string;
  options?: Option[];
  answer: string;
  accept?: string[];
  hints: string[];
  explanation: string;
  visual?: string;
  match?: 'value' | 'simplest' | 'exact' | 'mixed' | 'improper';
}
export interface Visual { id: string; alt: string; file?: string }
export interface Topic {
  id: string;
  title: string;
  status: 'draft' | 'verified' | 'approved' | 'retired';
  lesson: {
    hook: string;
    sections: { heading: string; body: string; visual?: string }[];
    examples: { problem: string; steps: string[]; answer: string }[];
    summary?: string[];
  };
  visuals?: Visual[];
  practice: Question[];
  quiz: Question[];
  doubts: { q: string; a: string }[];
}

const readJson = <T>(p: string): T => JSON.parse(fs.readFileSync(p, 'utf-8')) as T;

export function loadTopicMap(): TopicMap {
  return readJson<TopicMap>(path.join(REPO_ROOT, 'curriculum', 'topic-map.json'));
}

export function loadPublishedTopics(): Topic[] {
  const dir = path.join(REPO_ROOT, 'content', 'topics');
  const allowed = IS_PREVIEW ? ['approved', 'verified', 'draft'] : ['approved'];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => readJson<Topic>(path.join(dir, f)))
    .filter((t) => allowed.includes(t.status));
}

/** Inline SVG for a visual. Files are generated by our own scripts and checked by the verifier. */
export function visualSvg(topic: Topic, id: string | undefined): { svg: string; alt: string } | null {
  if (!id) return null;
  const v = topic.visuals?.find((x) => x.id === id);
  if (!v?.file) return null;
  const svg = fs.readFileSync(path.join(REPO_ROOT, v.file), 'utf-8');
  if (/<\s*script|\son[a-z]+\s*=|href\s*=/i.test(svg)) throw new Error(`Unsafe SVG in ${v.file}`);
  return { svg: svg.replace('<svg ', `<svg aria-hidden="true" focusable="false" `), alt: v.alt };
}
